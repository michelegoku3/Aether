#!/usr/bin/env python3
"""I-E: deterministic generator of the DLL<->Desk contract fixtures for the
manifest identity validator (D4).

The SAME binary blobs are consumed by:
  * AetherDLL/tests/quickwin_tests.cpp   ("manifest_contract" suite)
  * AetherDesk/src-tauri/src/tests/manifest_contract_tests.rs

If the format changes, regenerate here and update the table in TABLE.md
accordingly: the tests on both sides assert the same verdicts.
"""
import os
import struct

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "manifest")

PAYLOAD_MAGIC = 0x71F617D0
METADATA_MAGIC = 0x1F4812BE

DEPOT = 489831
GID = 4940892828028256588  # same value used by the historical Desk tests


def varint(value: int) -> bytes:
    out = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        if value == 0:
            out.append(byte)
            return bytes(out)
        out.append(byte | 0x80)


def frame(payload: bytes, metadata: bytes) -> bytes:
    out = bytearray()
    out += struct.pack("<I", PAYLOAD_MAGIC)
    out += struct.pack("<I", len(payload))
    out += payload
    out += struct.pack("<I", METADATA_MAGIC)
    out += struct.pack("<I", len(metadata))
    out += metadata
    return bytes(out)


def meta_basic(depot: int = DEPOT, gid: int = GID) -> bytes:
    """field 1 (depot) + field 2 (gid) + a length-delimited field to skip."""
    m = bytearray()
    m += varint((1 << 3) | 0) + varint(depot)
    m += varint((2 << 3) | 0) + varint(gid)
    m += varint((7 << 3) | 2) + varint(3) + b"abc"
    return bytes(m)


def meta_extra_wiretypes() -> bytes:
    """All supported wire types (0, 1, 2, 5) on unknown fields."""
    m = bytearray()
    m += varint((1 << 3) | 0) + varint(DEPOT)
    m += varint((3 << 3) | 1) + b"\x01" * 8          # wire 1: 64-bit
    m += varint((4 << 3) | 5) + b"\x02\x02\x03\x04"  # wire 5: 32-bit
    m += varint((7 << 3) | 2) + varint(2) + b"xy"    # wire 2: bytes
    m += varint((2 << 3) | 0) + varint(GID)
    m += varint((9 << 3) | 0) + varint(42)           # another varint
    return bytes(m)


FIXTURES = {}

# --- valid: identity readable from BOTH sides ---------------------------------
FIXTURES["valid_basic.bin"] = frame(b"payload-bytes", meta_basic())
FIXTURES["valid_extra_wiretypes.bin"] = frame(b"payload-2", meta_extra_wiretypes())

# --- malformed: both sides must reject ---------------------------------------
bad = bytearray(frame(b"payload-bytes", meta_basic()))
bad[0] ^= 0xFF  # breaks the payload magic
FIXTURES["bad_magic_payload.bin"] = bytes(bad)

bad = bytearray(frame(b"payload-bytes", meta_basic()))
bad[8 + len(b"payload-bytes")] ^= 0xFF  # breaks the metadata magic
FIXTURES["bad_magic_metadata.bin"] = bytes(bad)

# payload_len declares more bytes than exist
FIXTURES["truncated_payload.bin"] = frame(b"payload-bytes", meta_basic())[:14]

# metadata truncated mid-varint (gid field: dangling 0x80...)
full = frame(b"payload-bytes", meta_basic())
FIXTURES["truncated_metadata_varint.bin"] = full[: len(full) - 6]

# wire type 3 (group, unsupported) in metadata
bad_meta = varint((1 << 3) | 0) + varint(DEPOT) + varint((2 << 3) | 3) + b"\x00"
FIXTURES["bad_wire_type.bin"] = frame(b"payload-bytes", bad_meta)

FIXTURES["empty.bin"] = b""
FIXTURES["garbage_short.bin"] = b"\x01\x02\x03\x04\x05\x06\x07"

TABLE = """# Contract fixture — manifest identity (D4 / I-E)

Synthetic binary blobs, generated by `generate_manifest_fixtures.py`, consumed
IDENTICALLY by the C++ tests (quickwin_tests, `manifest_contract` suite) and the Rust
tests (`manifest_contract_tests.rs`). Expected `depot` = {depot}, expected `gid` = {gid}.

| file | expected verdict (both sides) |
|---|---|
| valid_basic.bin | identity = ({depot}, {gid}); match with expected; mismatch with different expected |
| valid_extra_wiretypes.bin | identity = ({depot}, {gid}) (wire types 0/1/2/5 skipped) |
| bad_magic_payload.bin | rejected |
| bad_magic_metadata.bin | rejected |
| truncated_payload.bin | rejected |
| truncated_metadata_varint.bin | rejected |
| bad_wire_type.bin | rejected |
| empty.bin | rejected |
| garbage_short.bin | rejected |

Note: a manifest without depot/gid fields declares identity (0,0). The C++
compares against the expected values (match only if 0 expected), Rust rejects
zero identities upfront — an INTENTIONAL documented divergence, not covered by this
table because verdicts differ by design.
""".format(depot=DEPOT, gid=GID)


def main() -> None:
    os.makedirs(OUT, exist_ok=True)
    for name, blob in FIXTURES.items():
        with open(os.path.join(OUT, name), "wb") as f:
            f.write(blob)
        print(f"{name}: {len(blob)} byte")
    with open(os.path.join(OUT, "TABLE.md"), "w", encoding="utf-8") as f:
        f.write(TABLE)
    print("TABLE.md written")


if __name__ == "__main__":
    main()
